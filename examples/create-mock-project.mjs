/**
 * End-to-end example for the project creation wizard.
 *
 * Requirements: API running, skills seeded (`npx prisma db seed`), and a valid
 * access token for the user who should own the sample project.
 *
 * Usage:
 *   API_BASE_URL=http://localhost:4000 ACCESS_TOKEN=<jwt> node examples/create-mock-project.mjs
 */

const baseUrl = (process.env.API_BASE_URL ?? "http://localhost:4000").replace(/\/$/, "");
const accessToken = process.env.ACCESS_TOKEN;

if (!accessToken) {
  throw new Error("Set ACCESS_TOKEN to a valid bearer token for the project owner.");
}

async function request(path, { method = "GET", body } = {}) {
  const response = await fetch(`${baseUrl}${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${accessToken}`,
      ...(body ? { "Content-Type": "application/json" } : {}),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
  });

  const result = await response.json().catch(() => ({}));
  if (!response.ok) {
    throw new Error(`${method} ${path} failed (${response.status}): ${JSON.stringify(result)}`);
  }
  return result;
}

// IDs are generated by the database, so resolve them by the stable catalogue
// names instead of hard-coding IDs that differ between environments.
const { skills: catalogue } = await request("/api/profile/skills");
const skillsByName = new Map(catalogue.map((skill) => [skill.name, skill]));

function skill(name, minLevel) {
  const match = skillsByName.get(name);
  if (!match) {
    throw new Error(`Skill “${name}” is missing. Seed the catalogue with: npx prisma db seed`);
  }
  return { skillId: match.id, minLevel };
}

// Future dates keep the sample valid whenever it is run.
